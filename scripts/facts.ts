#!/usr/bin/env bun
/**
 * Writes docs/facts.lima: what hadley.sh states about this repository, which it reads at a commit (sources.docs.data),
 * so that it states no version by hand. The gate checks the file.
 *
 *   bun scripts/facts.ts           write docs/facts.lima
 *   bun scripts/facts.ts --check   exit 1 if it differs
 *
 * Exit status: 0 written or the same, 1 it differs.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const repo = join(import.meta.dirname, '..')
const factsFile = join(repo, 'docs', 'facts.lima')

/** docs/facts.lima of a package's manifest: its version and those of its own parts. */
export function facts(manifest: { version: string; dependencies: Record<string, string> }): string {
  const part = (name: string) => {
    const range = manifest.dependencies[name]
    if (!range) throw new Error(`packages/hadley/package.json: no dependency ${name}`)
    return range.replace(/^\^/, '')
  }
  return `# Generated by scripts/facts.ts. Do not edit.
# Regenerate with: bun scripts/facts.ts

version: "${manifest.version}"
parts:
  lima: "${part('@limaformat/lima')}"
  markanto: "${part('@markantolang/parser')}"
  galley: "${part('@mkorun/galley')}"
  quad: "${part('@mkorun/quad')}"
`
}

if (import.meta.main) {
  const manifest = JSON.parse(readFileSync(join(repo, 'packages', 'hadley', 'package.json'), 'utf8'))
  const text = facts(manifest)
  if (process.argv.includes('--check')) {
    if (readFileSync(factsFile, 'utf8') !== text) {
      console.error('docs/facts.lima differs: run bun scripts/facts.ts')
      process.exit(1)
    }
  } else writeFileSync(factsFile, text)
}
